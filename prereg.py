"""事前登録した仮説を1回だけ測る（2026-08-16）

なぜ探索をやめるか
  これまで7世代・約28,000構成を探索し、1つも順列検定を通らなかった。
  理由は単純で、たくさん試して一番良いものを選ぶと、その「選ぶ」行為自体が
  数字を持ち上げるから。実測では
      20構成から選ぶ   → 翌年 -19.7pt
      2,509構成から選ぶ → 翌年 -70.5pt
  つまり探索の結果は、探索した回数ぶん割り引かないと意味がない。

そこでやり方を変える
  ① 統計的に確かめられている事実からだけ仮説を立てる
  ② ROIを見る前に仮説を固定する（このファイルに書いた時点で確定）
  ③ 1回だけ測る。悪ければ捨てる。良いものを探して条件をいじらない

使っている「確かめられている事実」は3つだけ
  事実1: モデルは1番人気の信頼度を見分けられる
         1番人気のMF複勝順位が1位のときと4位以下のときで、実際の複勝率が
         16.7ポイント違う（p=2.43e-10）。これは順列検定不要の水準。
  事実2: 市場は大穴を買いすぎる
         オッズ60倍超の実現/理論比 0.82、150倍超で 0.60。逆に59倍以下は
         1.00〜1.02でほぼ正確。→ 大穴は買わない、が唯一の確かな控除対策。
  事実3: 市場の重みはモデルの9倍（bet_cache）〜32.6倍（本番MF）
         → モデル単独で市場に勝つ買い方は作れない。市場を主、モデルを従に使う。

実行: python prereg.py
"""
import warnings

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")

from harness import Strategy, are_race, evaluate, load, report, solid_race


def log(m):
    print(m, flush=True)


# ── 事前登録した仮説（ROIを見る前に確定。あとから足さない）────────────
#
# H1〜H3: 事実1の裏側を使う。荒れR＝1番人気が信用できないレース。
#         そこでは1番人気以外の組み合わせに妙味があるはず。
# H4〜H5: 事実1の表側。堅いR＝1番人気が信用できるレース。順張りする。
# H6〜H8: 事実2。大穴を切ることが効くなら、上限オッズを絞るほど良くなるはず。
#
PREREG = [
    # ---- 荒れR（1番人気が信用できない）で、モデル上位を組む ----
    Strategy("H1 荒れR MF勝率1-2位 ワイド", "ワイド", "r1", 1, 2, (1, 20), are_race),
    Strategy("H2 荒れR MF勝率1-3位 ワイド", "ワイド", "r1", 1, 3, (1, 20), are_race),
    Strategy("H3 荒れR MF勝率1位 単勝", "単勝", "r1", 1, 1, (1, 20), are_race),

    # ---- 堅いR（1番人気が信用できる）で、順張りする ----
    Strategy("H4 堅いR MF複勝1位 複勝", "複勝", "r3", 1, 1, (1, 9999), solid_race),
    Strategy("H5 堅いR MF複勝1-3位 馬連", "馬連", "r3", 1, 3, (1, 9999), solid_race),

    # ---- 大穴を切る効果（現行A構成の上限を変えるだけ）----
    Strategy("H6 荒れR 勝率1x2 馬単裏 1-10倍", "馬単裏", "r1", 1, 2, (1, 10), are_race),
    Strategy("H7 荒れR 勝率1x2 馬単裏 1-20倍(現行A)", "馬単裏", "r1", 1, 2, (1, 20), are_race),
    Strategy("H8 荒れR 勝率1x2 馬単裏 1-40倍", "馬単裏", "r1", 1, 2, (1, 40), are_race),

    # ---- 相手側にも大穴除外をかける（事実2をもう一段）----
    Strategy("H9 荒れR 勝率1x2 馬単裏 相手も40倍以下", "馬単裏", "r1", 1, 2, (1, 20),
             are_race, mate_odds=(1, 40)),
]


def main():
    load()
    log(f"事前登録 {len(PREREG)}件。ROIを見る前に確定済み。あとから足さない。\n")
    log("使った事実:")
    log("  1) モデルは1番人気の信頼度を見分けられる（p=2.43e-10）")
    log("  2) 市場は60倍超を買いすぎる（比0.82）、59倍以下は正確（1.00-1.02）")
    log("  3) 市場の重みはモデルの9〜32.6倍\n")

    rows = [evaluate(s) for s in PREREG]
    R = report(rows)
    R.to_csv("prereg_result.csv", index=False, encoding="utf-8-sig")

    log("\n=== 採用できるか（3つとも満たすものだけ）===")
    log("  条件1: 5年通算 >= 100%")
    log("  条件2: 直近2年 >= 100%")
    log("  条件3: 7分前オッズでも >= 100%（実際に買えるか）")
    ok = R[(R["5年ROI"] >= 100) & (R["直近2年ROI"] >= 100) & (R["7分前ROI"] >= 100)]
    if len(ok):
        log(ok[["name", "点数", "的中", "5年ROI", "直近2年ROI", "7分前ROI",
                "CI下", "1R点数", "100超年"]].to_string(index=False))
    else:
        log("  なし")

    log("\n=== 事前登録の割引（9件試したことを考慮）===")
    log("  9件のうち偶然1件が100%を超える確率はそれなりにある。")
    log("  CI下限が100%を超えていれば、その1件は偶然では説明しにくい。")
    strong = R[R["CI下"] >= 100]
    log(strong[["name", "的中", "直近2年ROI", "CI下", "CI上"]].to_string(index=False)
        if len(strong) else "  CI下限が100%超のものは なし → どれも確定的な黒字ではない")


if __name__ == "__main__":
    main()
